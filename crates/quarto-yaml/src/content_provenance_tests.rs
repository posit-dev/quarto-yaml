#[test]
fn single_quoted_all_escape() {
    // `k: ''''` — one replacement piece (2 source bytes -> 1 content byte).
    // Must stay a 1-piece Concat, never collapse to `contiguous`: a
    // contiguous `Original` here would claim a byte-identical source range
    // this piece doesn't have, breaking the length invariant.
    let src = "k: ''''\n";
    let yaml = parse(src).unwrap();
    let v = yaml.get_hash_value("k").unwrap();
    let expected = concat(&[(0..1, 4..6)]);
    assert_eq!(v.content_source_info(), Some(&expected));
    assert!(
        !matches!(v.content_source_info(), Some(SourceInfo::Original { .. })),
        "a single replacement piece must not collapse to a contiguous SourceInfo"
    );
}

