#[test]
fn root_plain_col0_continuation() {
    // "aaa\nbbb\n" as a root-level plain scalar decodes to "aaa bbb": a
    // 1-byte fold whose source run (`\n`) and content (` `) are the same
    // *length* but not the same *bytes*. This is the only fixture that
    // binds the verbatim tag to byte-identity rather than length: every
    // other row's break region happens to be a byte-identical newline run,
    // so a buggy length-only rule would pass every other test here while
    // wrongly collapsing this one to a contiguous `Original(0, 7)`.
    let src = "aaa\nbbb\n";
    let yaml = parse(src).unwrap();
    let expected = concat(&[(0..3, 0..3), (3..4, 3..4), (4..7, 4..7)]);
    assert_eq!(yaml.content_source_info(), Some(&expected));
}

