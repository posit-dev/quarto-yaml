//! Failing tests for scalar content provenance (Phase 2 of
//! `claude-notes/plans/2026-08-20-provenance-1-foundations.md` in the q2
//! repo). Every test here transcribes a row from
//! `claude-notes/research/2026-08-21-yaml-content-provenance-fixtures.md`
//! and must be **RED** as of this commit: `content_source_info()` is `None`
//! for every scalar until the next task teaches the parser to derive and
//! attach it (see `YamlWithSourceInfo::content_source_info`'s doc comment
//! and the stub commit that introduced it).
//!
//! Per the fixtures note, do not re-derive expected values by hand — that
//! risks encoding this author's reading of YAML's folding rules instead of
//! the behavior the lockstep walker actually produces. Every expected piece
//! list below is transcribed from the note, which was generated by running
//! `claude-notes/research/yaml-content-provenance-walker/walker.rs` against
//! this crate and is itself the plan's stated authority for Phase 2.
//!
//! We assert the piece list (`SourceInfo::Original`/`SourceInfo::Concat`
//! and its `SourcePiece`s), not `map_offset` — this crate has no `tests/`
//! directory and constructs a `SourceContext` nowhere in `src/`, so routing
//! every fixture through `map_offset` would need an unbudgeted helper. A
//! `SourcePiece`'s fields are public and match the note's `content <-
//! source` notation directly. Two `map_offset` tests near the bottom cover
//! that contract instead.

use crate::parse;
use quarto_source_map::{FileId, SourceContext, SourceInfo};

/// The expected `SourceInfo` for a scalar whose derivation collapsed to a
/// single byte-identical run over `source[start..end]` — what
/// `ProvenanceBuilder::finish()` (quarto-source-map) emits for an all-file
/// scalar with exactly one *verbatim* piece, or none at all (the anchor
/// case: `finish()` on an empty piece list returns a zero-length `Original`
/// at the anchor, not `None` — see the fixtures note, "Provenance is
/// `Option`, and 'empty' is not `None`").
fn contiguous(start: usize, end: usize) -> SourceInfo {
    SourceInfo::original(FileId(0), start, end)
}

/// The expected `SourceInfo::Concat` for a scalar whose derivation produced
/// more than one piece, or exactly one piece that is a *replacement* (which
/// must not collapse to `contiguous` — see `single_quoted_all_escape`
/// below). `pieces` is `(content_range, source_range)` per piece, matching
/// the fixtures note's `content <- source` notation; `SourceInfo::concat`
/// computes each piece's `offset_in_concat` from the content ranges' order
/// and length, so passing the content range's length is enough.
fn concat(pieces: &[(std::ops::Range<usize>, std::ops::Range<usize>)]) -> SourceInfo {
    SourceInfo::concat(
        pieces
            .iter()
            .map(|(content, source)| (contiguous(source.start, source.end), content.len()))
            .collect(),
    )
}

