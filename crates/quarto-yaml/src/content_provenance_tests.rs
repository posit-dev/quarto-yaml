// ---------------------------------------------------------------------
// map_offset contract (kept minimal — the piece-list assertions above are
// the load-bearing tests; these three exercise `map_offset` itself)
// ---------------------------------------------------------------------

fn context_for(src: &str) -> SourceContext {
    let mut ctx = SourceContext::new();
    ctx.add_file("test.yaml".to_string(), Some(src.to_string()));
    ctx
}

#[test]
fn map_offset_contiguous_scalar() {
    let src = "k: 'hello'\n";
    let yaml = parse(src).unwrap();
    let v = yaml.get_hash_value("k").unwrap();
    let ctx = context_for(src);
    let si = v
        .content_source_info()
        .expect("derivation must produce Some");
    // Content offset 2 (the second 'l') is source offset 4 + 2 = 6.
    let mapped = si
        .map_offset(2, &ctx)
        .expect("offset within content must map");
    assert_eq!(mapped.location.offset, 6);
}

#[test]
fn map_offset_into_replacement_piece() {
    let src = "k: \"a\\tb\"\n";
    let yaml = parse(src).unwrap();
    let v = yaml.get_hash_value("k").unwrap();
    let ctx = context_for(src);
    let si = v
        .content_source_info()
        .expect("derivation must produce Some");
    // Content offset 1 (the decoded '\t') is inside the replacement piece
    // `1..2 <- 5..7`; per the contract, an offset inside a collapsed
    // region resolves to the start of that region: source offset 5.
    let mapped = si
        .map_offset(1, &ctx)
        .expect("offset within a replacement piece must map");
    assert_eq!(mapped.location.offset, 5);
}

#[test]
fn map_offset_at_content_end() {
    let src = "k: \"a\\tb\"\n";
    let yaml = parse(src).unwrap();
    let v = yaml.get_hash_value("k").unwrap();
    let ctx = context_for(src);
    let si = v
        .content_source_info()
        .expect("derivation must produce Some");
    // The exclusive end of the content (offset 3, the length of "a\tb")
    // maps like `Original`/`Substring`'s `map_offset(length)`: to the end
    // of the last piece, source offset 8.
    let mapped = si
        .map_offset(3, &ctx)
        .expect("offset at content end must map");
    assert_eq!(mapped.location.offset, 8);
}
